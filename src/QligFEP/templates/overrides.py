#: Section spelling used in the rendered input file.
SECTION_NAMES = {"md": "MD", "cut-offs": "cut-offs", "sphere": "sphere", "solvent": "solvent",
                 "intervals": "intervals", "pbc": "PBC"}  # fmt: skip

#: Sections QligFEP generates from the system being set up; overriding them would
#: silently fight the generator.
PROTECTED_SECTIONS = {
    "files",
    "lambdas",
    "sequence_restraints",
    "distance_restraints",
    "wall_restraints",
    "trajectory_atoms",
    "lambda_scaling",
}
#: Keys filled in per replicate by the run script.
PROTECTED_KEYS = {("md", "random_seed"), ("md", "initial_temperature")}


def apply_stage_override(
    params: MDParameters, override: StageOverride | None, stage: str
) -> MDParameters:
    """Return ``params`` with the protocol's overrides for ``stage`` applied.

    Raises:
        ConfigError: If the override touches a section or key QligFEP owns, or asks
            for a duration that is not a whole number of steps.
    """
    if override is None:
        return params
    where = f"stages.{stage}"
    changes: dict = {}
    extra = {section: dict(keys) for section, keys in params.extra.items()}

    for section, keys in override.inp.items():
        section_l = section.lower()
        if section_l in PROTECTED_SECTIONS:
            raise ConfigError(
                f"{where}.inp.{section}: this section is generated by QligFEP from the system "
                "being set up and cannot be overridden."
            )
        for key, value in keys.items():
            key_l = str(key).lower()
            if (section_l, key_l) in PROTECTED_KEYS:
                raise ConfigError(f"{where}.inp.{section}.{key}: set per replicate by the run script.")
            field_name = FIELD_MAP.get((section_l, key_l))
            if field_name is not None:
                changes[field_name] = value
                continue
            if section_l not in KNOWN_PASSTHROUGH:
                logger.warning(
                    f"{where}.inp: section [{section}] is not known to QligFEP; writing it as given."
                )
            elif key_l not in KNOWN_PASSTHROUGH[section_l]:
                logger.warning(
                    f"{where}.inp.{section}.{key}: not a qdyn keyword known to QligFEP; "
                    "passing it to qdyn as given."
                )
            extra.setdefault(SECTION_NAMES.get(section_l, section), {})[str(key)] = value

    stepsize = changes.get("stepsize", params.stepsize)
    steps = override.n_steps(float(stepsize), where)
    if steps is not None:
        changes["steps"] = steps
    return dataclasses.replace(params, **changes, extra=extra)
