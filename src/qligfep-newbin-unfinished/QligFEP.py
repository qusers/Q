class Write_Runfile():
    def __init__(self,wd,oldFEP,cluster):
        self.qdyn = SETTINGS.ROOT + 'src/bin/qdyn.py '
        self.qfep = SETTINGS.ROOT + 'bin/qfep.py '
        self.wd = wd
        self.oldFEProot = oldFEP.split('/')[-1]                
        self.cluster = cluster
        self.n_processes = 10
        self.commands = []
        
        self.topology = '../../inputfiles/dualtop.json'
        self.fepfile  = '../../inputfiles/FEP1.json'

        restart_deps = globaldata['restart_deps']
        for mdfile in globaldata['MDs']:
            restart = restart_deps[mdfile]
            if restart is None:
                # Root step (eq1): no restart flag
                command = "    os.system('python {} -c q7-gpu -t {} -m {}.json -f {} -d {} --clean')\n".format(self.qdyn,
                                                                            self.topology,
                                                                            mdfile,
                                                                            self.fepfile,
                                                                            mdfile
                                                                           )
            else:
                command = "    os.system('python {} -c q7-gpu -t {} -m ../../inputfiles/{}.json -f {} -d {} -r {}/dualtop/output --clean')\n".format(self.qdyn,
                                                                                  self.topology,
                                                                                  mdfile,
                                                                                  self.fepfile,
                                                                                  mdfile,
                                                                                  restart
                                                                           )
            self.commands.append(command)

        # add the qfep command
        command = "    os.system('python {} -d out -i ../../inputfiles/qfep.json')\n".format(self.qfep)
        self.commands.append(command)
        
        for T in globaldata['Temp']:
            self.T = T
            for replicate in globaldata['randrep']:
                self.r = replicate
                self.py = '{}/{}/run.py'.format(wd,
                                                self.oldFEProot,
                                               )
                self.write_py()
        
    def write_py(self):
        d = {
            'runfiles': '\n'.join(self.commands),
            'processors': self.n_processes
        }

        with open('{}/src/Qgpu/templates/RUN.py'.format(SETTINGS.ROOT), 'r') as f, \
             open(self.py,'w') as outfile:
            src = Template(f.read())
            result = src.substitute(d)
            outfile.write(result)

class Write_Submitfile():
    def __init__(self,wd,oldFEP,cluster):
        self.cluster = cluster
        self.oldFEProot = oldFEP.split('/')[-1]                
        
        if self.cluster != None:
            self.sh = '{}/{}/submit.sh'.format(wd,
                                self.oldFEProot,
                               )
            
        self.write_sh()
            
    def write_sh(self):
        with open(self.sh,'w') as outfile:
            outfile.write('#!/bin/bash\n')
            # construct slurm type file
            for key in SETTINGS.SLURM[self.cluster]:
                outfile.write('#SBATCH {} {}\n'.format(key,
                                                     SETTINGS.SLURM[self.cluster][key]
                                                    ))
            for module in SETTINGS.MODULES[self.cluster]:
                outfile.write('module load {}\n'.format(module))

            outfile.write('python run.py')

