class Write_MD():
    def __init__(self,wd,oldFEP):
        self.wd = wd
        self.oldFEP = oldFEP
        self.oldFEProot = oldFEP.split('/')[-1]
        self.lambdas = []

        # Collect all eq and md .inp files
        all_inp = sorted(glob.glob('{}/inputfiles/eq*.inp'.format(oldFEP))) + \
                  sorted(glob.glob('{}/inputfiles/md*.inp'.format(oldFEP)))

        # Build restart dependency graph w/ correct execution order
        restart_deps = parse_restart_deps(all_inp)
        globaldata['restart_deps'] = restart_deps
        bfs_order = execution_order(restart_deps)

        # Map stems to full paths for lookup
        inp_by_stem = {}
        for f in all_inp:
            stem = os.path.basename(f).split('.')[0]
            inp_by_stem[stem] = f

        mdfiles = [inp_by_stem[stem] for stem in bfs_order]

        for replicate in globaldata['randrep']:
            for i, md in enumerate(mdfiles):
                self.mdroot = md.split('/')[-1]
                self.mdroot = self.mdroot.split('.')[0]
                if not self.mdroot in globaldata['MDs']:
                    globaldata['MDs'].append(self.mdroot)

                md_data = self.construct(md)
                
                if 'md' in md or 'eq5' in md:
                    md_data['temperature'] = self.T
                
                if 'eq1' in md:
                    md_data['random_seed'] = globaldata['randrep'][replicate]
                    
                else:
                    md_data['random_seed'] = None

                # going to remove writing all MD files and implement lambdas instead
                if not md_data['lambdas'] in self.lambdas:
                    self.lambdas.append(md_data['lambdas'])    
                self.write(md_data, replicate)

        # Writing seeds and lambdas to seperate files

        IO.JSONdump(globaldata['seeds'],
                   '{}/{}/inputfiles/{}.json'.format(self.wd,
                                    self.oldFEProot,
                                    'seeds'))
        
        IO.JSONdump(self.lambdas,                    
                    '{}/{}/inputfiles/{}.json'.format(self.wd,
                                    self.oldFEProot,
                                    'lambdas'))
            
    def construct(self,md):
        read_md  = MD.Read_MD(md)
        md_data = read_md.Q()    

        return md_data
    
    def write(self,md_data, replicate):
        write_md = MD.Write_MD(md_data)
        if self.mdroot == 'eq1':
            for T in globaldata['Temp']:
                self.T = T
                self.r = replicate            
                out_json = '{}/{}/{:.1f}/{:02d}/{}.json'.format(self.wd,
                                                            self.oldFEProot,
                                                            self.T,
                                                            self.r,
                                                            self.mdroot,
                                                            )

                write_md.JSON(out_json)
            
        else:                
            out_json = '{}/{}/inputfiles/{}.json'.format(self.wd,
                                                       self.oldFEProot,
                                                       self.mdroot,
                                                      )
            
            write_md.JSON(out_json)

