def parse_restart_deps(inp_files):
    """Parse [files] sections from .inp files to build a restart dependency map.

    Returns dict mapping each file stem to its restart dependency stem,
    or None if the file has no restart (i.e. it's the root).
    """
    deps = {}
    for inp_path in inp_files:
        stem = os.path.basename(inp_path).split('.')[0]
        restart_dep = None
        in_files_block = False

        with open(inp_path) as f:
            for line in f:
                stripped = line.strip()
                if stripped.startswith('[') and stripped.endswith(']'):
                    in_files_block = (stripped == '[files]')
                    continue
                if in_files_block:
                    parts = stripped.split()
                    if len(parts) >= 2 and parts[0] == 'restart':
                        # restart field is like "eq1.re" - extract stem
                        restart_dep = parts[1].split('.')[0]

        deps[stem] = restart_dep
    return deps


def execution_order(restart_deps):
    """Compute execution order from restart dependency map.

    Produces radial interleaved order: eq1→eq5→midpoint, then
    forward/reverse pairs expanding outward from the midpoint (current default with start = 0.5).
    Children are sorted descending so forward chain (first lambda > 0.5)
    comes before reverse chain (first lambda < 0.5).
    """
    # Build children map (inverse of dependency)
    children = {}
    root = None
    for node, parent in restart_deps.items():
        if parent is None:
            root = node
        else:
            children.setdefault(parent, []).append(node)

    # Sort children descending so forward chain comes before reverse
    for parent in children:
        children[parent].sort(reverse=True)

    # BFS from root
    order = []
    queue = deque([root])
    while queue:
        node = queue.popleft()
        order.append(node)
        for child in children.get(node, []):
            queue.append(child)

    return order

class Random():
    """
        Gets total replicates, constructs a dictionary of random values per
        replicate
    """
    def __init__(self,replicates=10):        
        repdic = {}
        seeds = []
        for i in range(0, replicates):
            repdic[i] = randrange(0,9999)
            seeds.append(randrange(0,9999))

        globaldata['randrep'] = repdic
        globaldata['seeds'] = seeds

class Read_Submit():
    def __init__(self,oldFEP):        
        self.oldFEP = oldFEP
        self.submitfile = self.oldFEP + '/FEP_submit.sh'

        # get some data
        if os.path.isfile(self.submitfile) == True:
            self.get_data()
            
        else:
            print(">>> FATAL: can't find {}, is the specified directory generated by QligFEP?".format(self.submitfile))
            sys.exit()
        
    def get_data(self):
        with open(self.submitfile) as infile:
            for line in infile:
                line = line.split('=')
                if line[0] == 'runs':
                    globaldata['replicates']  = int(line[1])
                
                if line[0] == 'temperatures':
                    T = line[1][1:-2]
                    globaldata['Temp'].append(float(T))
                
class Create_Environment():
    def __init__(self,wd,oldFEP,overwrite):
        oldFEProot = oldFEP.split('/')[-1]
        if oldFEProot[-1] == '/':
            oldFEProot = oldFEProot[:-1]
        
        # create user specified main workdir
        IO.create_dir('{}'.format(wd),overwrite)
            
        # create FEPdir from old FEP
        IO.create_dir('{}/{}'.format(wd,oldFEProot),overwrite)
        
        # create inputfile dir
        IO.create_dir('{}/{}/{}'.format(wd,oldFEProot,'inputfiles'),overwrite)
        
        # create results dir
        IO.create_dir('{}/{}/{}'.format(wd,oldFEProot,'results'),overwrite)        

        # create temperature dirs
        for T in globaldata['Temp']:
            IO.create_dir('{}/{}/{:.1f}'.format(wd,oldFEProot,T),overwrite)

            # create replicate dirs
            for r in globaldata['randrep']:
                IO.create_dir('{}/{}/{:.1f}/{:02d}'.format(wd,oldFEProot,T,r),overwrite)
                
